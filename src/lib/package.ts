/**
 * Format de projet partagé : `.spp` — SuperPhoto Package.
 *
 * Un `.spp` est une **archive ZIP** ordinaire, lisible par n'importe quel outil
 * système (renommez-le en `.zip`), qui contient :
 *
 * ```
 * manifest.json                 index du paquet (une entrée par document)
 * README.txt                    ce que contient le fichier, en clair
 * preview.png                   aperçu du document actif
 * documents/doc-1.json          calques, textes, tracés, masques, modes
 * documents/doc-1/layer-1.png   pixels du calque 1, pleine résolution
 * documents/doc-1/mask-1.png    masque du calque 1, s'il existe
 * ```
 *
 * Les images ne sont **pas** en base64 : elles restent des PNG binaires, donc le
 * paquet est plus petit que la somme des `.sps` équivalents et chaque calque
 * reste ouvrable à la main dans n'importe quel éditeur.
 */
import { compositeCanvas } from './document';
import { t } from './i18n';
import type { BlendMode, ColorMode, Layer, LayerKind, PathData, PhotoDoc, ShapeData, TextData } from './types';
import { canvasContext, canvasToBlob, createCanvas } from './utils';
import { createZip, readText, readZip, type ZipEntry } from './zip';

export const SPP_EXTENSION = 'spp';
export const SPP_MIME = 'application/zip';
export const SPP_VERSION = 1;
export const SPP_FORMAT = 'superphoto-package';

interface PackagedLayer {
  id: string;
  name: string;
  kind: LayerKind;
  visible: boolean;
  opacity: number;
  blend: BlendMode;
  locked?: boolean;
  maskEnabled?: boolean;
  maskEditing?: boolean;
  /** Masque d'écretage (calque limité à l'alpha de celui du dessous). */
  clipToBelow?: boolean;
  text?: TextData;
  path?: PathData;
  shape?: ShapeData;
  /** Chemin du PNG dans l'archive. */
  image: string;
  mask?: string | null;
}

interface PackagedDocument {
  format: 'superphoto-document';
  version: number;
  name: string;
  width: number;
  height: number;
  dpi: number;
  colorMode: ColorMode;
  background: PhotoDoc['background'];
  activeLayerId: string;
  layers: PackagedLayer[];
}

interface PackagedIndexEntry {
  id: string;
  name: string;
  width: number;
  height: number;
  dpi: number;
  colorMode: ColorMode;
  layers: number;
  file: string;
}

interface PackagedIndex {
  format: typeof SPP_FORMAT;
  version: number;
  app: string;
  savedAt: string;
  activeIndex: number;
  documents: PackagedIndexEntry[];
}

const PREVIEW_EDGE = 720;

function slug(value: string, fallback: string): string {
  const clean = value
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
  return clean || fallback;
}

async function canvasBytes(canvas: HTMLCanvasElement): Promise<Uint8Array> {
  const blob = await canvasToBlob(canvas, 'image/png', 1);
  return new Uint8Array(await blob.arrayBuffer());
}

async function previewBytes(doc: PhotoDoc): Promise<Uint8Array> {
  const scale = Math.min(1, PREVIEW_EDGE / Math.max(doc.width, doc.height));
  const width = Math.max(1, Math.round(doc.width * scale));
  const height = Math.max(1, Math.round(doc.height * scale));
  const flat = compositeCanvas(doc, null);
  const small = createCanvas(width, height);
  const ctx = canvasContext(small);
  ctx.imageSmoothingQuality = 'high';
  ctx.drawImage(flat, 0, 0, width, height);
  return canvasBytes(small);
}

function readme(index: PackagedIndex): string {
  const lines = [
    'SuperPhoto package',
    '==================',
    '',
    `Saved: ${index.savedAt}`,
    `Documents: ${index.documents.length}`,
    '',
    'This file is a plain ZIP archive. Rename it to .zip to look inside, or',
    'open it directly in SuperPhoto with File > Open.',
    '',
    'manifest.json            package index',
    'documents/<id>.json      layers, text, paths, masks, colour mode',
    'documents/<id>/*.png     full-resolution layer pixels and masks',
    'preview.png              preview of the active document',
    '',
    'Documents',
    '---------',
  ];
  for (const entry of index.documents) {
    lines.push(`- ${entry.name} — ${entry.width} × ${entry.height} px · ${entry.dpi} dpi · ${entry.colorMode.toUpperCase()} · ${entry.layers} layer(s)`);
  }
  lines.push('', 'Generated by SuperPhoto.');
  return `${lines.join('\n')}\n`;
}

/** Sérialise un ou plusieurs documents dans une archive `.spp`. */
export async function serializePackage(
  docs: PhotoDoc[],
  activeIndex = 0,
): Promise<Blob> {
  if (docs.length === 0) throw new Error(t('pkg.noDocument'));

  const entries: ZipEntry[] = [];
  const indexEntries: PackagedIndexEntry[] = [];
  const encoder = new TextEncoder();

  for (let position = 0; position < docs.length; position += 1) {
    const doc = docs[position];
    if (!doc) continue;
    const id = `doc-${position + 1}`;
    const folder = `documents/${id}`;
    const layers: PackagedLayer[] = [];

    for (let index = 0; index < doc.layers.length; index += 1) {
      const layer = doc.layers[index];
      if (!layer) continue;
      const imagePath = `${folder}/layer-${index + 1}-${slug(layer.name, 'layer')}.png`;
      entries.push({ name: imagePath, data: await canvasBytes(layer.canvas) });
      let maskPath: string | null = null;
      if (layer.mask) {
        maskPath = `${folder}/mask-${index + 1}.png`;
        entries.push({ name: maskPath, data: await canvasBytes(layer.mask) });
      }
      layers.push({
        id: layer.id,
        name: layer.name,
        kind: layer.kind,
        visible: layer.visible,
        opacity: layer.opacity,
        blend: layer.blend,
        locked: layer.locked,
        maskEnabled: layer.maskEnabled,
        maskEditing: layer.maskEditing,
        clipToBelow: layer.clipToBelow,
        text: layer.text ? (JSON.parse(JSON.stringify(layer.text)) as TextData) : undefined,
        path: layer.path ? (JSON.parse(JSON.stringify(layer.path)) as PathData) : undefined,
      shape: layer.shape ? (JSON.parse(JSON.stringify(layer.shape)) as ShapeData) : undefined,
        image: imagePath,
        mask: maskPath,
      });
    }

    const colorMode: ColorMode = doc.colorMode ?? 'rgb';
    const document: PackagedDocument = {
      format: 'superphoto-document',
      version: SPP_VERSION,
      name: doc.name,
      width: doc.width,
      height: doc.height,
      dpi: doc.dpi,
      colorMode,
      background: doc.background,
      activeLayerId: doc.activeLayerId,
      layers,
    };
    const documentPath = `documents/${id}.json`;
    entries.push({
      name: documentPath,
      data: encoder.encode(JSON.stringify(document, null, 2)),
    });
    indexEntries.push({
      id,
      name: doc.name,
      width: doc.width,
      height: doc.height,
      dpi: doc.dpi,
      colorMode,
      layers: layers.length,
      file: documentPath,
    });
  }

  const active = Math.min(Math.max(0, activeIndex), Math.max(0, docs.length - 1));
  const activeDoc = docs[active];
  if (activeDoc) entries.push({ name: 'preview.png', data: await previewBytes(activeDoc) });

  const index: PackagedIndex = {
    format: SPP_FORMAT,
    version: SPP_VERSION,
    app: 'SuperPhoto',
    savedAt: new Date().toISOString(),
    activeIndex: active,
    documents: indexEntries,
  };
  entries.unshift({
    name: 'manifest.json',
    data: encoder.encode(JSON.stringify(index, null, 2)),
  });
  entries.push({ name: 'README.txt', data: encoder.encode(readme(index)) });

  return createZip(entries);
}

export function looksLikePackage(name: string): boolean {
  const lower = name.toLowerCase();
  return lower.endsWith(`.${SPP_EXTENSION}`) || lower.endsWith('.zip');
}

async function bytesToCanvas(
  bytes: Uint8Array,
  width: number,
  height: number,
): Promise<HTMLCanvasElement> {
  const copy = new Uint8Array(bytes.length);
  copy.set(bytes);
  const blob = new Blob([copy.buffer as ArrayBuffer], { type: 'image/png' });
  const bitmap = await createImageBitmap(blob);
  const canvas = createCanvas(width, height);
  const ctx = canvasContext(canvas);
  ctx.drawImage(bitmap, 0, 0);
  bitmap.close();
  return canvas;
}

function isPackagedDocument(raw: unknown): raw is PackagedDocument {
  if (!raw || typeof raw !== 'object') return false;
  const value = raw as PackagedDocument;
  return value.format === 'superphoto-document' && Array.isArray(value.layers);
}

/** Vrai si ce ZIP est un paquet SuperPhoto (testé sans décoder les images). */
export async function isSuperPhotoPackage(blob: Blob): Promise<boolean> {
  try {
    const files = await readZip(blob);
    const manifest = readText(files, 'manifest.json');
    if (!manifest) return false;
    return (JSON.parse(manifest) as PackagedIndex).format === SPP_FORMAT;
  } catch {
    return false;
  }
}

export interface OpenedPackage {
  docs: PhotoDoc[];
  activeIndex: number;
}

/** Lit une archive `.spp` et reconstruit les documents qu'elle contient. */
export async function parsePackage(blob: Blob): Promise<OpenedPackage> {
  const files = await readZip(blob);
  const manifest = readText(files, 'manifest.json');
  if (!manifest) throw new Error(t('pkg.notPackage'));
  let index: PackagedIndex;
  try {
    index = JSON.parse(manifest) as PackagedIndex;
  } catch {
    throw new Error(t('pkg.notPackage'));
  }
  if (index.format !== SPP_FORMAT || !Array.isArray(index.documents)) {
    throw new Error(t('pkg.notPackage'));
  }
  if (index.version > SPP_VERSION) throw new Error(t('pkg.tooRecent'));

  const docs: PhotoDoc[] = [];
  for (const entry of index.documents) {
    const text = readText(files, entry.file);
    if (!text) continue;
    let raw: unknown;
    try {
      raw = JSON.parse(text);
    } catch {
      continue;
    }
    if (!isPackagedDocument(raw)) continue;
    const width = Math.max(1, Math.round(Number(raw.width) || 1));
    const height = Math.max(1, Math.round(Number(raw.height) || 1));
    const layers: Layer[] = [];
    for (const stored of raw.layers) {
      const imageBytes = stored.image ? files.get(stored.image) : null;
      if (!imageBytes) continue;
      const layer: Layer = {
        id: stored.id,
        name: stored.name,
        kind: stored.kind ?? 'raster',
        visible: stored.visible !== false,
        opacity: typeof stored.opacity === 'number' ? stored.opacity : 1,
        blend: stored.blend ?? 'source-over',
        locked: Boolean(stored.locked),
        canvas: await bytesToCanvas(imageBytes, width, height),
        maskEnabled: stored.maskEnabled,
        maskEditing: stored.maskEditing,
        clipToBelow: stored.clipToBelow,
        text: stored.text,
        path: stored.path,
      shape: stored.shape,
      };
      const maskBytes = stored.mask ? files.get(stored.mask) : null;
      if (maskBytes) layer.mask = await bytesToCanvas(maskBytes, width, height);
      layers.push(layer);
    }
    if (layers.length === 0) continue;
    docs.push({
      name: raw.name || entry.name || 'SuperPhoto',
      width,
      height,
      dpi: Number(raw.dpi) || 72,
      colorMode: raw.colorMode ?? 'rgb',
      background: raw.background ?? 'transparent',
      layers,
      activeLayerId: layers.some((layer) => layer.id === raw.activeLayerId)
        ? raw.activeLayerId
        : (layers[layers.length - 1]?.id ?? ''),
    });
  }

  if (docs.length === 0) throw new Error(t('pkg.empty'));
  return { docs, activeIndex: Math.min(Math.max(0, index.activeIndex ?? 0), docs.length - 1) };
}
